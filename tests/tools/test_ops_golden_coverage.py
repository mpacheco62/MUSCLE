"""Coverage of the golden tests of the operators between tensor types (Phase 4, D-015).

The golden tests (`tests/tensors/operators/test_ops_golden_<module>.fypp`) check every computed
result, within the tolerance of its category (D-021), against `tests/reference/tensors/operators/ops_<module>_dp.txt` and fail if a
reference record is not produced or a result has no reference. These checks close the loop
against the inventory of the historical double precision operators,
`tools/fypp/ref/ops_signatures_dp.txt` (generated by `tools/fypp/ops_signatures.py` from the
original modules):

- the signatures of the reference files are exactly those of the inventory, each in the file of
  the module that defines its generic, each with the same cases 1..NCASES;
- the signature list embedded in `ops_golden_cases.fypp` is a verbatim copy of the inventory.
"""
import re
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
INVENTORY = ROOT / 'tools' / 'fypp' / 'ref' / 'ops_signatures_dp.txt'
REF_DIR = ROOT / 'tests' / 'reference' / 'tensors' / 'operators'
TEMPLATE = ROOT / 'tests' / 'tensors' / 'operators' / 'ops_golden_cases.fypp'
NCASES = 3

MODULE_GENERICS = {
    'addition_subtraction': {'operator(+)', 'operator(-)'},
    'assignment': {'assignment(=)'},
    'contraction_double': {'operator(.ddot.)'},
    'contraction_single': {'operator(*)'},
    'dyadic': {'operator(.tdot.)', 'operator(.tdotsym.)'},
    'transform': {'operator(.transform.)'},
}

# Number of stored values of each result type (size of `vals`).
NVALS = {
    'real(dp)': 1,
    'type(ten_2d2o)': 5, 'type(ten_3d2o)': 9,
    'type(ten_2d2osym)': 4, 'type(ten_3d2osym)': 6,
    'type(ten_2d4o2sym)': 16, 'type(ten_3d4o2sym)': 36,
    'type(ten_2d4o3sym)': 10, 'type(ten_3d4o3sym)': 21,
}


def inventory():
    return [l.strip() for l in INVENTORY.read_text(encoding='utf-8').splitlines() if l.strip()]


def references():
    """{module: [(signature, case, n, values)]} of the reference files."""
    out = {}
    for module in MODULE_GENERICS:
        records = []
        for line in (REF_DIR / f'ops_{module}_dp.txt').read_text(encoding='utf-8').splitlines():
            if not line.strip() or line.startswith('#'):
                continue
            sig, case, n, vals = line.split(' | ')
            records.append((sig, int(case.removeprefix('case ')), int(n), vals.split()))
        out[module] = records
    return out


def result_type(sig):
    if ' -> ' in sig:
        return sig.split(' -> ')[1]
    return sig.split(' (', 1)[1][:-1].split(', ')[0]   # assignment: the left-hand side


class TestOpsGoldenCoverage(unittest.TestCase):

    def test_inventory_has_222_signatures(self):
        sigs = inventory()
        self.assertEqual(len(sigs), 222)
        self.assertEqual(len(set(sigs)), 222)

    def test_references_cover_the_inventory(self):
        covered = set()
        for module, records in references().items():
            for sig, _, _, _ in records:
                self.assertIn(sig.split(' (', 1)[0], MODULE_GENERICS[module], f'{sig} in ops_{module}_dp.txt')
            covered |= {r[0] for r in records}
        self.assertEqual(sorted(covered), sorted(inventory()))

    def test_every_signature_has_every_case_once(self):
        for module, records in references().items():
            cases = {}
            for sig, case, _, _ in records:
                cases.setdefault(sig, []).append(case)
            for sig, got in cases.items():
                self.assertEqual(sorted(got), list(range(1, NCASES + 1)), f'{module}: {sig}')

    def test_values_are_complete_hex_bit_patterns(self):
        for module, records in references().items():
            for sig, case, n, vals in records:
                with self.subTest(module=module, sig=sig, case=case):
                    self.assertEqual(n, NVALS[result_type(sig)])
                    self.assertEqual(len(vals), n)
                    for v in vals:
                        self.assertRegex(v, r'^[0-9A-F]{16}$')
                        self.assertNotRegex(v, r'^[7F]FF[0-9A-F]', 'NaN/Inf in a golden value')

    def test_template_list_is_the_inventory(self):
        text = TEMPLATE.read_text(encoding='utf-8')
        block = text.split('#:set ALL_SIGNATURES = [', 1)[1].split(']\n', 1)[0]
        listed = re.findall(r"^\s*& '([^']+)',", block, re.M)
        self.assertEqual(listed, inventory())


if __name__ == '__main__':
    unittest.main()
