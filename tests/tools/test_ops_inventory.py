"""The operator table of `tools/fypp/muscle_meta.py` (`op_entries`) defines, in double precision, exactly
the operators of the original code: the inventory `tools/fypp/ref/ops_signatures_dp.txt` (generated by
`tools/fypp/ops_signatures.py` from the original modules, Phase 4, D-015). Every entry of the table is
checked against the operation on the full tensors by `tests/tensors/operators/test_muscle_tensor_ops_*_full.fypp`, so
together they cover every historical operator (this replaced the coverage check of the retired reference
operator tests, plan R).
"""
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
INVENTORY = ROOT / 'tools' / 'fypp' / 'ref' / 'ops_signatures_dp.txt'
sys.path.insert(0, str(ROOT / 'tools' / 'fypp'))
import muscle_meta  # noqa: E402


def signature(e):
    """Signature of an ``OpEntry`` in the format of the inventory:
    ``operator(+) (type(iden_2o), type(ten_3d2osym)) -> type(ten_3d2osym)``."""
    def typ(x):
        return x if x.startswith('real') else 'type({})'.format(x.lower().removesuffix('_dp'))
    generic = 'assignment(=)' if e.generic == '=' else 'operator({})'.format(e.generic)
    args = ', '.join(typ(x) for x in (e.a, e.b) if x)
    return '{} ({})'.format(generic, args) + (' -> {}'.format(typ(e.res)) if e.res else '')


class TestOpsInventory(unittest.TestCase):

    def test_table_is_the_inventory(self):
        inventory = [line.strip() for line in INVENTORY.read_text(encoding='utf-8').splitlines()
                     if line.strip()]
        self.assertEqual(len(inventory), 222)
        table = [signature(e) for g in muscle_meta.OP_GENERICS for d in muscle_meta.DIMS
                 for e in muscle_meta.op_entries(g, d, 'dp')]
        self.assertEqual(len(table), len(set(table)))
        self.assertEqual(sorted(table), sorted(inventory))


if __name__ == '__main__':
    unittest.main()
